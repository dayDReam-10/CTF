// transform core (plaintext after SMC): for each input byte b:
//     b = (b + 114 - 514) * 19 ; b ^= 19 ; b = rol32(b, 2) ; take low 8 bits
//   32 rows, one per byte, then call KSA -> call PRGA -> call verify -> halt.

static void SMC(void)
{
    for (size_t i = 0; i < sizeof(memory); ++i)
    {
        memory[i] ^= 0xAA;
    }
}

__attribute__((constructor(200)))
static void elf_init(void)
{
    SMC();

    if (anti_debug_detected)
    {
        memory[801] = ANTI_DEBUG_TRAP_ADDRESS;
        memory[803] = ANTI_DEBUG_TRAP_ADDRESS;
        memory[805] = ANTI_DEBUG_TRAP_ADDRESS;
    }
}

void vm_init(VM *vm, uint32_t *stack, uint8_t *data, uint32_t data_size)
{
    memset(vm, 0, sizeof(*vm));
    vm->code = memory;
    vm->stack = stack;
    vm->stack_size = STACK_SIZE;
    memcpy(memory + RW_BASE, data, data_size);
    vm->data = memory + RW_BASE;
    vm->data_size = data_size;
    vm->running = true;
}

static void vm_push(VM *vm, uint32_t value)
{
    vm->stack[vm->esp++] = value;
}

static uint32_t vm_pop(VM *vm)
{
    return vm->stack[--vm->esp];
}

void vm_execute(VM *vm)
{
    while (vm->running)
    {
        uint32_t opcode = vm->code[vm->ip++];
        switch (opcode)
        {
        case 0x01: // Mov R imm
        {
            uint32_t reg_index = vm->code[vm->ip++];
            uint32_t imm_num = vm->code[vm->ip++];
            vm->regs[reg_index] = imm_num;
            break;
        }
        case 0x02: // Mov R1 R2
        {
            uint32_t reg_index1 = vm->code[vm->ip++];
            uint32_t reg_index2 = vm->code[vm->ip++];
            vm->regs[reg_index1] = vm->regs[reg_index2];
            break;
        }
        case 0x03: // Add R imm
        {
            uint32_t reg_index = vm->code[vm->ip++];
            uint32_t imm_num = vm->code[vm->ip++];
            vm->regs[reg_index] += imm_num;
            break;
        }
        case 0x04: // Sub R imm
        {
            uint32_t reg_index = vm->code[vm->ip++];
            uint32_t imm_num = vm->code[vm->ip++];
            vm->regs[reg_index] -= imm_num;
            break;
        }
        case 0x05: // Mul R imm
        {
            uint32_t reg_index = vm->code[vm->ip++];
            uint32_t imm_num = vm->code[vm->ip++];
            vm->regs[reg_index] *= imm_num;
            break;
        }
        case 0x06: // rol_left R imm
        {
            uint32_t reg_index = vm->code[vm->ip++];
            uint32_t imm = vm->code[vm->ip++];
            vm->regs[reg_index] = (vm->regs[reg_index] << imm) | (vm->regs[reg_index] >> (32 - imm));
            break;
        }
        case 0x07: // xor R imm
        {
            uint32_t reg_index = vm->code[vm->ip++];
            uint32_t imm_num = vm->code[vm->ip++];
            vm->regs[reg_index] ^= imm_num;
            break;
        }
        case 0x08: // cmp R1 R2
        {
            uint32_t reg_index1 = vm->code[vm->ip++];
            uint32_t reg_index2 = vm->code[vm->ip++];
            vm->eq = (vm->regs[reg_index1] == vm->regs[reg_index2]);
            break;
        }
        case 0x09: // call addr = push + jmp
        {
            uint32_t addr = vm->code[vm->ip++];

            if (addr == ANTI_DEBUG_TRAP_ADDRESS)
            {
                anti_debug_trap();
                break;
            }

            vm_push(vm, vm->ip);

            if (addr == 0xF0) // KSA
            {
                rc4_ksa(rc4_state, rc4_key, sizeof(rc4_key) - 1);
                vm->ip = vm_pop(vm);
                break;
            }

            if (addr == 0xF1) // PRGA
            {
                rc4_prga(rc4_state, vm->data, vm->data_size);
                vm->ip = vm_pop(vm);
                break;
            }

            if (addr == 0xF2) // verify: memcmp(data, Answer, FLAG_LEN)
            {
                vm->eq = (vm->data_size == FLAG_LEN) &&
                         (memcmp(vm->data, memory + ANSWER_BASE, FLAG_LEN) == 0);
                vm->ip = vm_pop(vm);
                break;
            }

            vm->ip = addr;
            break;
        }
        case 0x0A: // ret
        {
            vm->ip = vm_pop(vm);
            break;
        }
        case 0xFD: // load input[index] -> R
        {
            uint32_t reg_index = vm->code[vm->ip++];
            vm->regs[reg_index] = vm->data[vm->transform_index];
            break;
        }
        case 0xF7: // store R -> data[index], advance (unrolled: no loop)
        {
            uint32_t reg_index = vm->code[vm->ip++];
            vm->data[vm->transform_index++] = (uint8_t)vm->regs[reg_index];
            break;
        }
        case 0xFF: // halt
            vm->running = false;
            break;
        }
    }
}

int main(void)
{
    char input[DATA_SIZE];
    uint32_t stack[STACK_SIZE];
    VM vm;

    fputs("Input flag: ", stdout);
    fflush(stdout);
    if (fgets(input, sizeof(input), stdin) == NULL)
        return EXIT_FAILURE;

    input[strcspn(input, "\r\n")] = '\0';
    if (strlen(input) != FLAG_LEN)
    {
        puts("Wrong.");
        return EXIT_FAILURE;
    }

    vm_init(&vm, stack, (uint8_t *)input, (uint32_t)strlen(input));
    vm_execute(&vm);

    puts(vm.eq ? "Correct." : "Wrong.");
    return vm.eq ? EXIT_SUCCESS : EXIT_FAILURE;
}
